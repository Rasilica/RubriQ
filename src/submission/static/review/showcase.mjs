import { element, button, badge, field } from "./primitives.mjs";

const grid = element("div", "showcase-grid");
const controls = element("section", "panel stack");
controls.append(element("h2", "", "버튼과 상태"));
const actions = element("div", "cluster");
actions.append(button("변경사항 저장", () => {}, "primary"), button("원문 보기", () => {}));
const waiting = button("저장 중", () => {}, "primary");
waiting.disabled = true;
actions.append(waiting);
controls.append(actions, badge("필수"), badge("테스트 응답", true));
controls.append(element("p", "notice", "저장한 변경사항을 확인한 뒤 기준을 확정하세요."));
const error = element("p", "notice error", "저장하지 못했습니다. 입력 내용은 유지됩니다.");
error.setAttribute("role", "alert");
controls.append(error);
const form = element("section", "panel stack");
form.append(element("h2", "", "입력과 오류"));
form.append(field({ id:"example-title",label:"요구사항 제목",value:"문제와 대상 사용자",onChange:()=>{} }));
form.append(field({ id:"example-kind",label:"구분",value:"conditional",options:[["required","필수"],["conditional","조건부"]],onChange:()=>{} }));
const reason = field({ id:"example-reason",label:"적용 확인 사유",multiline:true,help:"적용 여부를 선택한 이유를 적어주세요.",onChange:()=>{} });
reason.querySelector("textarea").setAttribute("aria-invalid", "true");
reason.append(element("p", "error-text", "사유가 필요합니다."));
form.append(reason);
const paper = element("section", "panel paper stack");
paper.append(element("h2", "", "원문과 선택"));
const row = element("button", "requirement-row");
row.type="button"; row.setAttribute("aria-current","true");
row.append(element("strong","","긴 제목도 안전하게 줄바꿈하는 요구사항 선택 상태"), badge("선택됨"));
paper.append(row);
const quote = element("p", "original-text", "원문에서 ");
quote.append(element("mark", "", "정확히 선택한 인용 범위"), document.createTextNode("를 확인합니다.\n한국어 문장은 읽기 좋은 간격을 유지합니다."));
paper.append(quote, element("p","mono","0123456789abcdef".repeat(8)));
const details = element("details");
details.append(element("summary", "", "이전 확정 기준"), element("p", "muted", "확정한 기준이 아직 없습니다."));
paper.append(details);
grid.append(controls,form,paper);
document.querySelector("#showcase").append(grid);
